const I18N_KEY = "gta6-lang";

function getLang() {
  const saved = localStorage.getItem(I18N_KEY);
  if (saved === "he" || saved === "en") return saved;
  return (navigator.language || "en").toLowerCase().startsWith("he") ? "he" : "en";
}

function applyLang(lang) {
  const dict = I18N[lang] || I18N.en;
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "he" ? "rtl" : "ltr";
  document.body.classList.toggle("lang-he", lang === "he");

  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      if (el.tagName === "TITLE") el.textContent = dict[key];
      else el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll(".stat-num").forEach(el => {
    const heSuf = el.getAttribute("data-suffix-he");
    const enSuf = el.getAttribute("data-suffix") || "";
    el.dataset.activeSuffix = (lang === "he" && heSuf) ? heSuf : enSuf;
  });

  const flag = document.getElementById("langFlag");
  const code = document.getElementById("langCode");
  if (flag && code) {
    flag.textContent = dict.switchTo.flag;
    code.textContent = dict.switchTo.code;
  }

  window.__lang = lang;
  window.__dict = dict;
  document.dispatchEvent(new CustomEvent("langchange", { detail: { lang, dict } }));
}

function setLang(lang) {
  localStorage.setItem(I18N_KEY, lang);
  applyLang(lang);
}

document.addEventListener("DOMContentLoaded", () => {
  applyLang(getLang());
  const btn = document.getElementById("langSwitch");
  if (btn) btn.addEventListener("click", () => {
    setLang(window.__lang === "he" ? "en" : "he");
  });
});
